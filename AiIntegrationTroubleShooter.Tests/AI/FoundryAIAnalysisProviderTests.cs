    [Fact]
    public async Task AnalyseAsync_ValidJson_ReturnsAnalysisResponse()
    {
        // Arrange
        var jsonResponse = """
        {
            "summary": "The connection to the target system failed.",
            "possibleCauses": [
                {
                    "cause": "The target system is unavailable.",
                    "confidence": "Medium",
                    "reasoning": "The connection failure may indicate that the target system is unavailable."
                }
            ],
            "investigationSteps": [
                "Check whether the target system is running.",
                "Check network connectivity."
            ],
            "warnings": [
                "This analysis is generated by AI and requires verification."
            ],
            "requiresHumanReview": true
        }
        """;

        var mockChatClient = new Mock<IChatClient>();

        mockChatClient
            .Setup(x => x.GetResponseAsync(
                It.IsAny<IEnumerable<ChatMessage>>(),
                It.IsAny<ChatOptions?>(),
                It.IsAny<CancellationToken>()))
            .ReturnsAsync(
                new ChatResponse(
                    new ChatMessage(ChatRole.Assistant, jsonResponse)));

        var provider = CreateProvider(mockChatClient);

        var request = new IntegrationIssueRequest
        {
            IntegrationName = "Test integration",
            SourceSystem = "System A",
            TargetSystem = "System B",
            ErrorMessage = "Connection failed"
        };

        // Act
        var result = await provider.AnalyseAsync(request);

        // Assert
        Assert.Equal(
            "The connection to the target system failed.",
            result.Summary);

        Assert.Single(result.PossibleCauses);
        Assert.Equal("Medium", result.PossibleCauses[0].Confidence);

        Assert.Equal(2, result.InvestigationSteps.Count);
        Assert.True(result.RequiresHumanReview);
    }

