using AiIntegrationTroubleShooter.Api.Contracts;

namespace AiIntegrationTroubleShooter.Api.AI;

public class FakeAIAnalysisProvider : IAIAnalysisProvider
{
    public Task<IntegrationAnalysisResponse> AnalyseAsync(
        IntegrationIssueRequest request,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var response = new IntegrationAnalysisResponse
        {
            Summary = "The integration failed while communicating with the target system."
        };

        response.PossibleCauses.Add(new PossibleCause
        {
            Cause = "The target system rejected the request.",
            Confidence = "Medium",
            Reasoning = "The integration error indicates a possible rejection by the receiving system."
        });

        response.InvestigationSteps.Add(
            "Check the error message returned by the target system.");

        response.InvestigationSteps.Add(
            "Verify that the integration request contains valid data.");

        response.InvestigationSteps.Add(
            "Check the target system logs.");

        response.Warnings.Add(
            "This is a simulated response and has not been generated by an AI model.");

        response.RequiresHumanReview = true;

        return Task.FromResult(response);
    }
}
